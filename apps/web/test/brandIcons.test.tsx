import { render, screen } from '@testing-library/react';
import axe from 'axe-core';
import { describe, expect, it } from 'vitest';
import { SERVICE_CATALOG } from '@subcycle/shared';
import { ServiceIcon } from '../src/components/ui/display';
import { BRAND_ICONS } from '../src/lib/brandIcons.generated';
import { buildCreatePayload, buildUpdatePayload, emptyValues, iconFromText, textFromIcon, valuesFromSubscription } from '../src/lib/subscriptionForm';
import { makeSub } from './helpers';
import generatedSource from '../src/lib/brandIcons.generated.ts?raw';

describe('brand logos bundled with the app', () => {
  it('every logo key the catalogue uses exists, and no logo is shipped that nothing uses', () => {
    const used = new Set(SERVICE_CATALOG.map((s) => s.logo).filter((l): l is string => l !== null));
    expect([...used].filter((k) => !(k in BRAND_ICONS))).toEqual([]);
    expect(Object.keys(BRAND_ICONS).filter((k) => !used.has(k))).toEqual([]);
  });

  it('each logo is well-formed: path logos are path data only, image logos are inert SVG data URIs', () => {
    for (const [key, icon] of Object.entries(BRAND_ICONS)) {
      expect(key).toMatch(/^[a-z0-9-]{1,32}$/);
      expect(icon.title.length, key).toBeGreaterThan(0);
      if (icon.path !== undefined) {
        expect(icon.hex, key).toMatch(/^[0-9A-Fa-f]{6}$/);
        expect(icon.path, key).toMatch(/^[MmLlHhVvCcSsQqTtAaZz0-9eE.,\s-]+$/); // SVG path commands and numbers: no markup, no scripts
        expect(icon.path.length, key).toBeLessThan(6000);
      } else {
        expect(icon.image, key).toMatch(/^data:image\/svg\+xml;charset=utf-8,/);
        const svg = decodeURIComponent(icon.image!.split(',').slice(1).join(','));
        expect(svg, key).toMatch(/^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 [\d.]+ [\d.]+">/);
        expect(svg, key).not.toMatch(/<\s*(script|foreignObject|iframe|image|use)\b|\son[a-z]+\s*=|href\s*=|javascript:|@import|url\(\s*['"]?https?:/i); // nothing active, nothing external
        expect(svg.length, key).toBeLessThan(8000);
      }
    }
    expect(Object.keys(BRAND_ICONS).length).toBeGreaterThanOrEqual(60);
    expect(Object.values(BRAND_ICONS).some((i) => i.image)).toBe(true);
  });

  it('the generated file carries its generator, licence and trademark notice', () => {
    const head = generatedSource.slice(0, 700);
    expect(head).toMatch(/GENERATED by scripts\/generate-brand-icons\.mjs/);
    expect(head).toMatch(/CC0-1\.0/);
    expect(head).toMatch(/trademark of its owner/);
  });
});

describe('ServiceIcon', () => {
  const sub = (icon: { kind: 'glyph' | 'emoji'; value: string } | null) => ({ name: 'Netflix', category: 'video' as const, icon });

  it('draws the bundled logo for a known key, as a decorative tile (the name is shown next to it)', () => {
    const { container } = render(<ServiceIcon subscription={sub({ kind: 'glyph', value: 'netflix' })} />);
    const tile = container.querySelector('[data-logo="netflix"]')!;
    expect(tile).toHaveAttribute('aria-hidden', 'true');
    expect(tile.querySelector('svg path')?.getAttribute('d')).toBe(BRAND_ICONS.netflix!.path);
    expect(tile.querySelector('img')).toBeNull(); // nothing is loaded from anywhere
    expect(tile.querySelector('svg')?.getAttribute('fill')).toBe(`#${BRAND_ICONS.netflix!.hex}`);
  });

  it('draws a full-colour logo as an inline image (never as markup), with no alt text because the name is next to it', () => {
    const { container } = render(<ServiceIcon subscription={sub({ kind: 'glyph', value: 'slack-icon' })} />);
    const tile = container.querySelector('[data-logo="slack-icon"]')!;
    const img = tile.querySelector('img')!;
    expect(img.getAttribute('src')).toBe(BRAND_ICONS['slack-icon']!.image);
    expect(img.getAttribute('src')).toMatch(/^data:image\/svg\+xml/); // same-origin policy: nothing remote
    expect(img).toHaveAttribute('alt', '');
    expect(tile.querySelector('svg')).toBeNull();
  });

  it('falls back to a letter tile for an unknown key, and keeps emoji working', () => {
    const unknown = render(<ServiceIcon subscription={sub({ kind: 'glyph', value: 'not-a-real-logo' })} />);
    expect(unknown.container.querySelector('svg')).toBeNull();
    expect(unknown.container.textContent).toBe('N');
    unknown.unmount();
    const emoji = render(<ServiceIcon subscription={sub({ kind: 'emoji', value: '🎬' })} />);
    expect(emoji.container.textContent).toBe('🎬');
    emoji.unmount();
    const none = render(<ServiceIcon subscription={sub(null)} />);
    expect(none.container.textContent).toBe('N');
  });

  it('a page full of logos has no accessibility violations', async () => {
    render(
      <ul>
        {Object.keys(BRAND_ICONS).slice(0, 20).map((k) => (
          <li key={k}>
            <ServiceIcon subscription={{ name: BRAND_ICONS[k]!.title, category: 'video', icon: { kind: 'glyph', value: k } }} />
            {BRAND_ICONS[k]!.title}
          </li>
        ))}
      </ul>,
    );
    const r = await axe.run(document.body, { rules: { 'color-contrast': { enabled: false }, region: { enabled: false } } });
    expect(r.violations.map((v) => v.id)).toEqual([]);
    expect(screen.getAllByRole('listitem')).toHaveLength(20);
  });
});

describe('the Icon form field: an emoji or a built-in logo key', () => {
  const base = () => ({ ...emptyValues('INR'), name: 'Netflix', amountMinor: '149', nextBillingDate: '2030-02-01' });

  it('maps text to the stored icon shape and back', () => {
    expect(iconFromText('🎬')).toEqual({ kind: 'emoji', value: '🎬' });
    expect(iconFromText(' netflix ')).toEqual({ kind: 'glyph', value: 'netflix' });
    expect(iconFromText('')).toBeNull();
    expect(textFromIcon({ kind: 'glyph', value: 'netflix' })).toBe('netflix');
    expect(textFromIcon(null)).toBe('');
  });

  it('creates with a logo key and with an emoji; refuses an unknown key', () => {
    const logo = buildCreatePayload({ ...base(), icon: 'netflix' }, { today: '2030-01-15' });
    expect(logo.ok && logo.payload.icon).toEqual({ kind: 'glyph', value: 'netflix' });
    const emoji = buildCreatePayload({ ...base(), icon: '🎬' }, { today: '2030-01-15' });
    expect(emoji.ok && emoji.payload.icon).toEqual({ kind: 'emoji', value: '🎬' });
    const bad = buildCreatePayload({ ...base(), icon: 'netflixx' }, { today: '2030-01-15' });
    expect(bad.ok).toBe(false);
    expect(!bad.ok && bad.errors.icon).toMatch(/built-in logo/);
  });

  it('editing: an unchanged logo sends nothing; changing or clearing it sends only the icon', () => {
    const s = makeSub({ icon: { kind: 'glyph', value: 'netflix' } });
    const v = valuesFromSubscription(s);
    expect(v.icon).toBe('netflix');
    const same = buildUpdatePayload(v, s, { today: '2030-01-15' });
    expect(!same.ok && same.nothingChanged).toBe(true);
    const swap = buildUpdatePayload({ ...v, icon: '🎬' }, s, { today: '2030-01-15' });
    expect(swap.ok && swap.payload).toEqual({ icon: { kind: 'emoji', value: '🎬' } });
    const clear = buildUpdatePayload({ ...v, icon: '' }, s, { today: '2030-01-15' });
    expect(clear.ok && clear.payload).toEqual({ icon: null });
  });
});
