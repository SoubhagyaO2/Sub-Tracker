#!/usr/bin/env node
// Regenerates apps/web/src/lib/brandIcons.generated.ts: the SVG paths of the brand logos the built-in service list refers to.
// The logos come from the `simple-icons` package (dev dependency, CC0-1.0 licensed artwork). They are trademarks of their owners
// and are used only to identify the service they belong to. Run after changing a `logo` key in packages/shared/src/services.ts:
//   npm run build -w @subcycle/shared && node scripts/generate-brand-icons.mjs
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import * as simpleIcons from 'simple-icons';
import { SERVICE_CATALOG } from '../packages/shared/dist/index.js';

const bySlug = new Map(Object.values(simpleIcons).filter((v) => v && v.slug && v.path).map((v) => [v.slug, v]));
const wanted = [...new Set(SERVICE_CATALOG.map((s) => s.logo).filter(Boolean))].sort();
const missing = wanted.filter((slug) => !bySlug.has(slug));
if (missing.length) {
  console.error(`Not in simple-icons: ${missing.join(', ')}. Fix the catalogue (use null for "no logo").`);
  process.exit(1);
}
const entries = wanted.map((slug) => {
  const i = bySlug.get(slug);
  return `  ${JSON.stringify(slug)}: { title: ${JSON.stringify(i.title)}, hex: ${JSON.stringify(i.hex)}, path: ${JSON.stringify(i.path)} },`;
});
const out = `// GENERATED by scripts/generate-brand-icons.mjs: do not edit by hand.
// Artwork: Simple Icons (https://simpleicons.org), CC0-1.0. Each logo is a trademark of its owner; it is shown only to identify
// the service a user is tracking, and does not imply any affiliation with or endorsement by that owner.
export interface BrandIcon {
  title: string;
  /** Brand colour, without the leading #. */
  hex: string;
  /** SVG path data for a 24 x 24 viewBox. */
  path: string;
}

export const BRAND_ICONS: Readonly<Record<string, BrandIcon>> = {
${entries.join('\n')}
};
`;
const target = path.resolve(import.meta.dirname, '../apps/web/src/lib/brandIcons.generated.ts');
writeFileSync(target, out);
console.log(`Wrote ${wanted.length} logos (${Math.round(out.length / 1024)} KB) to ${path.relative(process.cwd(), target)}`);
