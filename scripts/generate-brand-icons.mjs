#!/usr/bin/env node
// Regenerates apps/web/src/lib/brandIcons.generated.ts: the logos the built-in service list refers to.
// Two free, CC0-licensed artwork collections are used (both dev dependencies, bundled at build time, never fetched at run time):
//   - simple-icons              (single-colour logos as SVG paths)  https://simpleicons.org
//   - @iconify-json/logos       (full-colour "SVG Logos")          https://github.com/gilbarbara/logos
// A logo key that exists in simple-icons wins; otherwise the key is looked up in SVG Logos. The logos are trademarks of their
// owners and are used only to identify the service. Run after changing a `logo` key in packages/shared/src/services.ts:
//   npm run build -w @subcycle/shared && node scripts/generate-brand-icons.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import * as simpleIcons from 'simple-icons';
import { SERVICE_CATALOG } from '../packages/shared/dist/index.js';

const require = createRequire(path.resolve(import.meta.dirname, '../apps/web/package.json'));
const logos = require('@iconify-json/logos/icons.json');

const bySlug = new Map(Object.values(simpleIcons).filter((v) => v && v.slug && v.path).map((v) => [v.slug, v]));
const wanted = [...new Set(SERVICE_CATALOG.map((s) => s.logo).filter(Boolean))].sort();

const UNSAFE = /<\s*(script|foreignObject|iframe|image|use)\b|\son[a-z]+\s*=|(?:xlink:)?href\s*=|javascript:|<!ENTITY|@import|url\(\s*['"]?https?:/i;
const prettify = (key) => key.replace(/-icon$/, '').replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());

const entries = [];
const missing = [];
for (const key of wanted) {
  const simple = bySlug.get(key);
  if (simple) {
    entries.push(`  ${JSON.stringify(key)}: { title: ${JSON.stringify(simple.title)}, hex: ${JSON.stringify(simple.hex)}, path: ${JSON.stringify(simple.path)} },`);
    continue;
  }
  const full = logos.icons[key];
  if (!full) {
    missing.push(key);
    continue;
  }
  if (UNSAFE.test(full.body)) {
    console.error(`Refusing ${key}: its SVG contains scripts, links or external references.`);
    process.exit(1);
  }
  const w = full.width ?? logos.width;
  const h = full.height ?? logos.height;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${full.body}</svg>`;
  entries.push(`  ${JSON.stringify(key)}: { title: ${JSON.stringify(prettify(key))}, image: ${JSON.stringify(`data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`)} },`);
}
if (missing.length) {
  console.error(`Not in either collection: ${missing.join(', ')}. Fix the catalogue (use null for "no logo").`);
  process.exit(1);
}

const out = `// GENERATED by scripts/generate-brand-icons.mjs: do not edit by hand.
// Artwork: Simple Icons (https://simpleicons.org, CC0-1.0) and SVG Logos (https://github.com/gilbarbara/logos, CC0-1.0).
// Each logo is a trademark of its owner; it is shown only to identify the service a user is tracking, and does not imply any
// affiliation with or endorsement by that owner.
export type BrandIcon =
  /** A single-colour logo drawn from SVG path data (24 x 24 viewBox) in the brand colour. */
  | { title: string; hex: string; path: string; image?: undefined }
  /** A full-colour logo as an SVG data URI, drawn with <img> (scripts in an SVG never run when shown that way). */
  | { title: string; image: string; hex?: undefined; path?: undefined };

export const BRAND_ICONS: Readonly<Record<string, BrandIcon>> = {
${entries.join('\n')}
};
`;
const target = path.resolve(import.meta.dirname, '../apps/web/src/lib/brandIcons.generated.ts');
writeFileSync(target, out);
console.log(`Wrote ${entries.length} logos (${Math.round(out.length / 1024)} KB) to ${path.relative(process.cwd(), target)}`);
